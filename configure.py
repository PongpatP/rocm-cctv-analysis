#!/usr/bin/env python3
"""Generate all runtime configs from config.local.yaml (single source of truth).

    ./configure.py

Reads  config.local.yaml (falls back to config.example.yaml with a warning)
Writes gateway/go2rtc.yaml     — streams + ports for the go2rtc gateway
       webapp/config.json      — NVR topology + bridge port for the web UI
       ai/configs/cameras.yaml — camera list + pipeline settings for the detector
       ai/configs/config_infer_primary_yolo26.txt — legacy detector engine config

Generated files are gitignored; credentials exist only in config.local.yaml.
"""

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent


def load():
    local = ROOT / "config.local.yaml"
    cfg = None
    if local.exists():
        cfg = yaml.safe_load(local.read_text())
    if cfg is not None:
        # NVRs managed from the web UI (Settings → Cameras & NVRs) live in a
        # separate overlay so this file's comments and credentials survive.
        cls = ROOT / "output" / "ai_classes.json"
        if cls.exists():
            try:
                data = json.loads(cls.read_text())
                sel = data.get("selected") if isinstance(data, dict) else data
                if isinstance(sel, list) and sel:
                    cfg.setdefault("ai", {})["class_filter"] = sel
            except ValueError:
                pass
        override = ROOT / "output" / "nvrs_override.json"
        if override.exists():
            try:
                data = json.loads(override.read_text())
                if isinstance(data.get("nvrs"), list) and data["nvrs"]:
                    cfg["nvrs"] = data["nvrs"]
                # single cameras with arbitrary RTSP URLs (forwarded ports,
                # other brands) — first-class alongside NVR channels
                if isinstance(data.get("cameras"), list):
                    cfg["extra_cameras"] = [
                        c for c in data["cameras"]
                        if isinstance(c, dict) and c.get("id") and c.get("url")]
            except ValueError:
                print("WARNING: output/nvrs_override.json is broken — ignored")
        return cfg
    print("WARNING: config.local.yaml not found — using config.example.yaml")
    print("         copy it to config.local.yaml and fill in real values")
    return yaml.safe_load((ROOT / "config.example.yaml").read_text())


def active_channels(nvr):
    skip = set(nvr.get("skip") or [])
    return [ch for ch in range(1, nvr["channels"] + 1) if ch not in skip]


def cam_key(nvr, ch):
    return f"{nvr['id']}_ch{ch:02d}"


def write_go2rtc(cfg):
    gw = cfg["gateway"]
    upstream = gw.get("upstream", "direct")
    fw = gw.get("forwarder") or {}
    if upstream == "forwarder" and not fw.get("host"):
        sys.exit("gateway.upstream is 'forwarder' but gateway.forwarder.host is not set")
    # Ports here are compose-internal; the proxy publishes gateway.web_port.
    lines = [
        "# GENERATED by configure.py — edit config.local.yaml, not this file.",
        "",
        "api:",
        '  listen: ":1984"',
        '  static_dir: "/webapp"',
        "",
        "rtsp:",
        '  listen: ":8554"',
        "",
        "log:",
        f'  level: {gw.get("log_level", "info")}',
        "",
        "streams:",
    ]
    n = 0
    for nvr in cfg["nvrs"]:
        for ch in active_channels(nvr):
            for profile, subtype in (("sub", 1), ("main", 0)):
                name = f"{cam_key(nvr, ch)}_{profile}"
                if upstream == "forwarder":
                    # upstream go2rtc relay serves the same stream names
                    url = f"rtsp://{fw['host']}:{fw.get('port', 8554)}/{name}"
                else:
                    url = (
                        f"rtsp://{nvr['user']}:{nvr['password']}@{nvr['host']}:{nvr['port']}"
                        f"/cam/realmonitor?channel={ch}&subtype={subtype}"
                    )
                lines.append(f"  {name}: {url}")
                n += 1
    for cam in cfg.get("extra_cameras") or []:
        lines.append(f"  {cam['id']}_main: {cam['url']}")
        lines.append(f"  {cam['id']}_sub: {cam.get('url_sub') or cam['url']}")
        n += 1
    (ROOT / "gateway" / "go2rtc.yaml").write_text("\n".join(lines) + "\n")
    return n


