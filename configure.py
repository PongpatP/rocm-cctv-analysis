def write_infer(cfg, n_cameras):
    gpu = int(cfg.get("ai", {}).get("gpu_id", 0))
    model = cfg.get("ai", {}).get("model", "yolo26s")
    engine = ROOT / "ai" / "models" / f"{model}_fp16_gpu{gpu}.engine"
    if not engine.exists():
        print(f"WARNING: {engine.name} not built yet — run: scripts/setup_model.sh {model}")
    (ROOT / "ai" / "configs" / "config_infer_primary_yolo26.txt").write_text(
        INFER_TEMPLATE.format(model=model, batch=min(n_cameras, 32), gpu=gpu)
    )
    pose = cfg.get("ai", {}).get("pose", {})
    if pose.get("enabled"):
        pmodel = pose.get("model", "yolo26l-pose")
        pengine = ROOT / "ai" / "models" / f"{pmodel}_fp16_gpu{gpu}.engine"
        if not pengine.exists():
            print(f"WARNING: {pengine.name} not built yet — export the "
                  f"ONNX and run trtexec (see ai/scripts/build_trt_engine.sh)")
        (ROOT / "ai" / "configs" / "config_infer_pose_yolo26.txt").write_text(
            POSE_TEMPLATE.format(model=pmodel, batch=min(n_cameras, 32),
                                 interval=int(pose.get("interval", 0)),
                                 gpu=gpu)
        )
        print(f"ai pose config           model={pmodel}")
    depth = cfg.get("ai", {}).get("depth", {})
    if depth.get("enabled"):
        dmodel = depth.get("model", "dav2s-depth")
        dengine = ROOT / "ai" / "models" / f"{dmodel}_fp16_gpu{gpu}.engine"
        if not dengine.exists():
            print(f"WARNING: {dengine.name} not built yet")
        (ROOT / "ai" / "configs" / "config_infer_depth_dav2.txt").write_text(
            DEPTH_TEMPLATE.format(model=dmodel, batch=min(n_cameras, 32),
                                  interval=int(depth.get("interval", 1)),
                                  gpu=gpu)
        )
        print(f"ai depth config          model={dmodel}")
    return model


def write_webapp(cfg):
    out = {
        "classes": cfg.get("ai", {}).get("class_filter") or [],
        "model": cfg.get("ai", {}).get("model", "yolo26s"),
        "aspect": cfg.get("ui", {}).get("aspect", "16:9"),
        "nvrs": [
            {
                "id": nvr["id"],
                "name": nvr["name"],
                "host": nvr["host"],
                "channels": nvr["channels"],
                "skip": nvr.get("skip") or [],
            }
            for nvr in cfg["nvrs"]
        ],
    }
    out["extra_cameras"] = [
        {"id": c["id"], "name": c.get("name") or c["id"]}
        for c in cfg.get("extra_cameras") or []]
    (ROOT / "webapp" / "config.json").write_text(json.dumps(out, indent=2) + "\n")


def write_ai(cfg):
    ai = cfg["ai"]
    gw = cfg["gateway"]
    wanted = ai.get("cameras", "all")

    cameras = []
    for nvr in cfg["nvrs"]:
        for ch in active_channels(nvr):
            key = cam_key(nvr, ch)
            if wanted == "all" or key in wanted:
                # compose-internal DNS name of the gateway service
                cameras.append(
                    {"id": key, "uri": f"rtsp://gateway:8554/{key}_main"}
                )
    for cam in cfg.get("extra_cameras") or []:
        if wanted == "all" or cam["id"] in wanted:
            cameras.append({"id": cam["id"],
                            "uri": f"rtsp://gateway:8554/{cam['id']}_main"})
    if not cameras:
        sys.exit("ai.cameras matched no channels — check config.local.yaml")

    out = {
        "gpu_id": ai.get("gpu_id", 0),
        "streammux": ai.get("streammux", {}),
        "inference": {
            "config": "configs/config_infer_primary_yolo26.txt",
            "interval": ai.get("infer_interval", 0),
        },
        "pose": {
            "enabled": bool(ai.get("pose", {}).get("enabled")),
            "config": "configs/config_infer_pose_yolo26.txt",
            "min_confidence": float(
                ai.get("pose", {}).get("min_confidence", 0.35)),
        },
        "depth": {
            "enabled": bool(ai.get("depth", {}).get("enabled")),
            "config": "configs/config_infer_depth_dav2.txt",
            "publish_dir": "output/calib/track23/live",
            "publish_fps": float(
                ai.get("depth", {}).get("publish_fps", 2.0)),
        },
        "tracker": {
            **ai.get("tracker", {"enabled": True}),
            "config": "configs/config_tracker_NvDCF.yml",
        },
        "output": {
            "jsonl": {"enabled": False, "path": "output/detections.jsonl"},
            "http": {
                "enabled": True,
                "url": "http://bridge:8081/ingest",
                "batch_size": 50,
                "flush_interval_s": 0.3,
                "timeout_s": 5,
            },
        },
        # Detector floor: matches pre-cluster-threshold. The user-facing
        # threshold is applied live by the bridge (web UI -> AI settings).
        "min_confidence": 0.10,
        "class_filter": ai.get("class_filter", []),
        "cameras": cameras,
    }
    text = (
        "# GENERATED by configure.py — edit config.local.yaml, not this file.\n"
        + yaml.safe_dump(out, sort_keys=False)
    )
    (ROOT / "ai" / "configs" / "cameras.yaml").write_text(text)
    return len(cameras)


def main():
    cfg = load()
    n_streams = write_go2rtc(cfg)
    write_webapp(cfg)
    n_cams = write_ai(cfg)
    model = write_infer(cfg, n_cams)
    print(f"gateway/go2rtc.yaml      {n_streams} streams")
    print(f"webapp/config.json       ok")
    print(f"ai/configs/cameras.yaml  {n_cams} cameras")
    print(f"ai infer config          model={model}")
    print("apply with: docker compose up -d")


if __name__ == "__main__":
    main()
